// 대분류 이름 목록 (선택 상자 순서)
export const treeNames = (tree) => tree.map((m) => m.name);

// 대분류 이름으로 소분류 목록을 찾습니다. 없는 대분류는 빈 목록입니다.
export function subsOf(tree, major) {
  return tree.find((m) => m.name === major)?.subs ?? [];
}
